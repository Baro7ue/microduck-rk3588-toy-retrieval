"""Writes tests/fixtures.h: the answers unit_tests.cpp checks against, computed with the Python
code the C++ must match (cv2.resize, views.to_input, uyvy.decode, detect.decode_split).

    PYTHONPATH=src python cpp/board_bench/tests/make_fixtures.py

The inputs are not stored: both sides generate them (pattern() for images and payloads, the LCG
for raw NPU outputs), so the header stays small. Run again only if a generator changes.
"""
from __future__ import annotations

from pathlib import Path

import cv2
import numpy as np

from microduck_toy.vision import detect, uyvy, views

OUT = Path(__file__).resolve().parent / 'fixtures.h'


def lcg(seed: int):
    x = seed & 0xffffffff
    while True:
        x = (x * 1664525 + 1013904223) & 0xffffffff
        yield x >> 8


def fnv1a(data: bytes) -> int:
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xffffffffffffffff
    return h


def pattern(h: int, w: int, salt: int) -> np.ndarray:
    """h x w x 3 uint8: (r*7 + c*13 + ch*29 + (r*c) % 11 + salt) % 256."""
    r, c, ch = np.meshgrid(np.arange(h), np.arange(w), np.arange(3), indexing='ij')
    return ((r * 7 + c * 13 + ch * 29 + (r * c) % 11 + salt) % 256).astype(np.uint8)


def payload_pattern() -> bytes:
    i = np.arange(640 * 360 * 2, dtype=np.int64)
    return ((i * 31 + (i >> 9) * 7 + 3) % 256).astype(np.uint8).tobytes()


SCALE_CLS = np.float32(1.0 / 255.0)
HOT_EVERY = 20


def raw_outputs(seed: int):
    """Raw INT8 outputs as the C++ test makes them: (q int8 NCHW, zp, scale) per output."""
    rnd = lcg(seed)
    outs = []
    for stride in detect.STRIDES:
        g = 320 // stride
        box = np.array([(next(rnd) % 256) - 128 for _ in range(64 * g * g)], np.int8).reshape(1, 64, g, g)
        # Per cell: hot with chance 1/HOT_EVERY, its class constant over 3x3 blocks of cells, so
        # neighbouring hot cells overlap and NMS has work; the other scores stay below 0.08.
        cls = np.empty((1, 6, g, g), np.int8)
        for y in range(g):
            for x in range(g):
                hot = next(rnd) % HOT_EVERY == 0
                c_hot = (y // 3 + x // 3) % 6
                for ch in range(6):
                    r = next(rnd)
                    cls[0, ch, y, x] = (-128 + 70 + (r >> 4) % 186 if hot and ch == c_hot
                                        else -128 + (r >> 4) % 20)
        hot = (cls[0] > -128 + 40).any(axis=0)
        ssum = np.empty((g, g), np.int8)
        for y in range(g):
            for x in range(g):
                r = next(rnd)
                ssum[y, x] = 127 if hot[y, x] else -128 + r % 30
        outs += [(box, 0, np.float32(0.25)), (cls, -128, SCALE_CLS), (ssum[None, None], -128, SCALE_CLS)]
    return outs


def dequant(q, zp, scale):
    return (q.astype(np.float32) - np.float32(zp)) * np.float32(scale)


def main() -> None:
    lines = ['// Generated by make_fixtures.py; do not edit.', '#pragma once', '#include <cstdint>', '']

    small = pattern(7, 9, 3)
    lines.append('// cv2.resize(pattern(7, 9, 3), (5, 4), INTER_LINEAR), row-major RGB')
    out = cv2.resize(small, (5, 4), interpolation=cv2.INTER_LINEAR)
    lines.append('static const uint8_t kResizeSmall[] = {' + ', '.join(map(str, out.ravel())) + '};')
    big = {
        'kResize360To320': cv2.resize(pattern(360, 360, 5), (320, 320), interpolation=cv2.INTER_LINEAR),
        'kResize640x360To320x180': cv2.resize(pattern(640, 360, 7), (180, 320),
                                              interpolation=cv2.INTER_LINEAR),
    }
    for name, img in big.items():
        lines.append(f'static const uint64_t {name} = 0x{fnv1a(img.tobytes()):016x}ULL;')

    pay = payload_pattern()
    pairs = np.frombuffer(pay, np.uint8).reshape(360, 320, 4)
    upright = np.ascontiguousarray(np.rot90(uyvy.decode(pairs), 3))
    lines += ['', '// uyvy.decode + rot90(3) of payload_pattern(): rows 137..496, and all 640 rows',
              f'static const uint64_t kDecodeRows137 = 0x{fnv1a(upright[137:497].tobytes()):016x}ULL;',
              f'static const uint64_t kDecodeAll = 0x{fnv1a(upright.tobytes()):016x}ULL;']
    window = views.Mapping('window', 0.0, 137.0, views.INPUT / views.WINDOW, 0.0, 0.0)
    lines += ['', '// views.to_input of that frame: window at y0 = 137, and letterbox',
              f'static const uint64_t kInputWindow137 = 0x{fnv1a(views.to_input(upright, window).tobytes()):016x}ULL;',
              f'static const uint64_t kInputLetterbox = '
              f'0x{fnv1a(views.to_input(upright, views.letterbox_mapping()).tobytes()):016x}ULL;']

    seed = 2024
    raw = raw_outputs(seed)
    floats = [dequant(*o) for o in raw]
    boxes, scores, classes = detect.decode_split(floats, 0.25, 0.45)
    # Candidates before NMS, to make sure the case is a real test (NMS acts, scores tie) and that
    # no same-class pair sits within 1e-4 of the IoU threshold (float32 vs float64 DFL).
    cand = []
    for k, stride in enumerate(detect.STRIDES):
        cls, ssum = floats[3 * k + 1], floats[3 * k + 2]
        ys, xs = np.nonzero(ssum[0, 0] >= 0.25 - detect.SUM_MARGIN)
        sc = cls[0][:, ys, xs]
        cand += [s for s in sc.max(axis=0) if s > 0.25]
    one = detect.decode_split(floats, 0.25, 1.01)  # no suppression: every candidate
    b1, c1 = one[0], one[2]
    ious = []
    for i in range(len(b1)):
        for j in range(i + 1, len(b1)):
            if c1[i] == c1[j]:
                a, b = b1[i], b1[j]
                w = max(0, min(a[2], b[2]) - max(a[0], b[0]))
                h = max(0, min(a[3], b[3]) - max(a[1], b[1]))
                inter = w * h
                union = (a[2] - a[0]) * (a[3] - a[1]) + (b[2] - b[0]) * (b[3] - b[1]) - inter
                ious.append(inter / union if union > 0 else 0)
    margin = min(abs(v - 0.45) for v in ious)
    ties = len(cand) - len(set(np.round(cand, 7)))
    assert margin > 1e-4, margin
    assert len(boxes) < len(cand) and ties > 0, (len(boxes), len(cand), ties)
    lines += ['', f'// detect.decode_split(conf 0.25, iou 0.45) on raw_outputs({seed}): {len(cand)} candidates,',
              f'// {ties} tied scores, {len(boxes)} kept; closest same-class IoU to 0.45 is {margin:.4f} away.',
              f'static const uint32_t kDecodeSeed = {seed};',
              f'static const uint32_t kHotEvery = {HOT_EVERY};',
              'struct ExpectedBox { float x0, y0, x1, y1, score; int cls; };',
              'static const ExpectedBox kDecodeExpected[] = {']
    for b, s, c in zip(boxes, scores, classes):
        lines.append(f'    {{{b[0]:.5f}f, {b[1]:.5f}f, {b[2]:.5f}f, {b[3]:.5f}f, {s:.8f}f, {int(c)}}},')
    lines.append('};')
    OUT.write_text('\n'.join(lines) + '\n')
    print(f'{OUT}: {len(boxes)} boxes from {len(cand)} candidates, {ties} ties, margin {margin:.4f}')


if __name__ == '__main__':
    main()
